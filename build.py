"""
Project page builder for the portfolio site.

How to use:
  1. Drop a project PDF into the "Projects Folder".
  2. Run:  python build.py
  3. Open projects.html. Each PDF now has an entry in the list, and clicking it
     opens its own page showing that PDF.

What this script touches:
  - projects.html: ONLY the part between the AUTO-PROJECTS START/END comments.
    Your hand-written project entries (Phobos, FPV Cinelifter, ...) are never edited.
  - project-pages/: one generated page per PDF. Deleted and rebuilt on every run.
Generated pages also load scrollicon.js (the scroll icon). Nothing else is modified.

Optional: to give a project a picture on the Projects page, save an image in
the img folder with the same name as the PDF, e.g. "Level 1 Rocket.pdf" ->
img/Level 1 Rocket.jpg (.jpg, .jpeg, .png or .webp).
"""

import html
import re
import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent
PDF_DIR = ROOT / "Projects Folder"
PAGES_DIR = ROOT / "project-pages"
IMG_DIR = ROOT / "img"
PROJECTS_HTML = ROOT / "projects.html"

START = "<!-- AUTO-PROJECTS:START (generated by build.py, do not edit between these lines) -->"
END = "<!-- AUTO-PROJECTS:END -->"
IMAGE_TYPES = (".jpg", ".jpeg", ".png", ".webp")


def esc(text):
    return html.escape(text, quote=True)


def slugify(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "project"


def make_title(stem):
    """my_cool-project -> 'My Cool Project'. Names with capitals are kept as typed."""
    spaced = re.sub(r"[_\-]+", " ", stem).strip()
    return spaced.title() if spaced.islower() else spaced


def find_image(stem):
    for ext in IMAGE_TYPES:
        candidate = IMG_DIR / (stem + ext)
        if candidate.exists():
            return candidate.name
    return None


def find_projects():
    PDF_DIR.mkdir(exist_ok=True)
    pdfs = sorted(
        (p for p in PDF_DIR.iterdir() if p.is_file() and p.suffix.lower() == ".pdf"),
        key=lambda p: p.name.lower(),
    )
    projects, used = [], set()
    for pdf in pdfs:
        base = slugify(pdf.stem)
        slug, n = base, 2
        while slug in used:
            slug = f"{base}-{n}"
            n += 1
        used.add(slug)
        projects.append(
            {
                "title": make_title(pdf.stem),
                "slug": slug,
                "file": pdf.name,
                "image": find_image(pdf.stem),
            }
        )
    return projects


def card_html(p):
    """Same markup as the hand-written project entries in projects.html."""
    return (
        '        <div class="project">\n'
        '          <div class="image-container">\n'
        '            <img src="./img/spacex.jpg">\n'
        "          </div>\n"
        '          <div class="project-info">\n'
        f'            <a href="project-pages/{p["slug"]}.html">{esc(p["title"])}</a>\n'
        f"            <p> The world needs to know more about {esc(p["title"])}! Quickly, add the summary here. Don't forget to update the project image too!</p>\n"
        "          </div>\n"
        "        </div>\n"
    )


def page_html(p):
    """Same header and navbar as the other pages, paths adjusted for the subfolder."""
    pdf = f"../{quote(PDF_DIR.name)}/{quote(p['file'])}"
    title = esc(p["title"])
    return f"""<!DOCTYPE html>
<html lang="en">

<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Noah Niesen</title>
  <link rel="stylesheet" href="../stylesheet.css">
</head>

<body>
  <div class="container">
    <div class="header">
      <h1>Noah Niesen</h1>
    </div>
    <div class="navbar">
      <button onclick="document.location='../index.html'" type="button" class="btn btn-default btn3d">About</button>
      <button onclick="document.location='../projects.html'" id="midBtn" type="button"
        class="btn btn-default btn3d">Projects</button>
      <button onclick="document.location='../contact.html'" href="" type="button"
        class="btn btn-default btn3d">Contact</button>
    </div>

    <div style="display:flex; flex-direction:column; align-items:center; margin-bottom:20px;">
      <iframe src="{pdf}" title="{title} (PDF)" style="width:80%; height:80vh; border:1px solid black;"></iframe>
    </div>
  </div>
  <script src="../scrollicon.js"></script>
</body>

</html>
"""


def update_projects_page(projects):
    raw = PROJECTS_HTML.read_bytes()
    uses_crlf = b"\r\n" in raw
    text = raw.decode("utf-8").replace("\r\n", "\n")

    start_at = text.find(START)
    end_at = text.find(END)
    if start_at == -1 or end_at == -1 or end_at < start_at:
        sys.exit(
            "Could not find the AUTO-PROJECTS comments in projects.html.\n"
            "Put these two lines inside the projects-container, after your last project:\n"
            f"  {START}\n  {END}"
        )

    # Keep the END comment's own indentation.
    line_start = text.rfind("\n", 0, end_at) + 1
    end_indent = text[line_start:end_at]
    block_start = text.index("\n", start_at) + 1
    new_block = "".join(card_html(p) for p in projects)
    new_text = text[:block_start] + new_block + end_indent + text[end_at:]

    out = new_text.replace("\n", "\r\n") if uses_crlf else new_text
    PROJECTS_HTML.write_bytes(out.encode("utf-8"))


def main():
    projects = find_projects()

    PAGES_DIR.mkdir(exist_ok=True)
    for old in PAGES_DIR.glob("*.html"):
        old.unlink()
    for p in projects:
        (PAGES_DIR / f"{p['slug']}.html").write_text(
            page_html(p), encoding="utf-8", newline="\r\n"
        )

    update_projects_page(projects)

    print(f"Done. {len(projects)} project(s) from 'Projects Folder':")
    for p in projects:
        print(f"  {p['file']}  ->  project-pages/{p['slug']}.html")
    if not projects:
        print("  (no PDFs found - add some to 'Projects Folder' and run again)")


if __name__ == "__main__":
    main()
